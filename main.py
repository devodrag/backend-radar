"""
Backend Tech Radar & Daily Pulse Generator
Zero external dependencies (uses standard library urllib, json, datetime).
"""

import os
import json
import datetime
import urllib.request
import urllib.error

USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) BackendRadarBot/1.0"

def fetch_json(url, headers=None):
    if headers is None:
        headers = {}
    headers["User-Agent"] = USER_AGENT
    
    # Use GITHUB_TOKEN if available to avoid GitHub API rate limits
    github_token = os.environ.get("GITHUB_TOKEN")
    if "api.github.com" in url and github_token:
        headers["Authorization"] = f"Bearer {github_token}"
        
    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except Exception as e:
        print(f"[-] Warning: Failed to fetch {url}: {e}")
        return None

def get_trending_github_repos():
    """Fetch top active backend repositories in Go, C++, Python, and C#."""
    seven_days_ago = (datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=7)).strftime("%Y-%m-%d")
    
    queries = [
        ("Go", f"language:go+created:>{seven_days_ago}+stars:>15"),
        ("C++", f"language:c%2B%2B+created:>{seven_days_ago}+stars:>10"),
        ("Python", f"language:python+topic:backend+stars:>20"),
        ("C# / .NET", f"language:csharp+created:>{seven_days_ago}+stars:>10")
    ]
    
    results = {}
    for lang, q in queries:
        url = f"https://api.github.com/search/repositories?q={q}&sort=stars&order=desc&per_page=3"
        data = fetch_json(url)
        if data and "items" in data:
            results[lang] = [
                {
                    "name": item["full_name"],
                    "url": item["html_url"],
                    "stars": item["stargazers_count"],
                    "description": item["description"] or "No description provided."
                }
                for item in data["items"][:3]
            ]
        else:
            results[lang] = []
    return results

def get_top_hn_stories():
    """Fetch top engineering & tech stories from Hacker News."""
    top_ids_url = "https://hacker-news.firebaseio.com/v0/topstories.json"
    ids = fetch_json(top_ids_url)
    if not ids:
        return []
    
    stories = []
    # Pick top 5 stories
    for item_id in ids[:10]:
        item_url = f"https://hacker-news.firebaseio.com/v0/item/{item_id}.json"
        story = fetch_json(item_url)
        if story and "title" in story and "url" in story:
            stories.append({
                "title": story["title"],
                "url": story.get("url", f"https://news.ycombinator.com/item?id={item_id}"),
                "score": story.get("score", 0),
                "comments": story.get("descendants", 0)
            })
        if len(stories) >= 5:
            break
    return stories

def generate_markdown(date_str, repos_by_lang, hn_stories):
    lines = []
    lines.append(f"# 🛰️ Backend Tech Radar // {date_str}\n")
    lines.append(f"> Automated telemetry and curated technical intelligence. Generated by `devodrag/backend-radar`.\n")
    lines.append("## ⚡ Trending Repositories by Ecosystem\n")
    
    for lang, repos in repos_by_lang.items():
        lines.append(f"### `{lang}`\n")
        if not repos:
            lines.append("_No new notable repos detected today._\n")
            continue
        for r in repos:
            lines.append(f"- **[{r['name']}]({r['url']})** (`★ {r['stars']}`)")
            lines.append(f"  _{r['description']}_\n")
            
    lines.append("## 📰 Top Engineering & Tech Discussions\n")
    if hn_stories:
        for s in hn_stories:
            lines.append(f"- [{s['title']}]({s['url']}) — `▲ {s['score']} pts` | `💬 {s['comments']} comments`")
    else:
        lines.append("_Discussions feed unavailable today._")
        
    lines.append("\n---\n<sub>( • ) devodrag · Automated telemetry</sub>\n")
    return "\n".join(lines)

def update_root_readme(date_str, repos_by_lang, hn_stories):
    content = [
        '<div align="center">',
        '  <p><code><b>( • ) BACKEND TECH RADAR &nbsp;|&nbsp; AUTOMATED DAILY PULSE</b></code></p>',
        f'  <h1><b>RADAR // {date_str}</b></h1>',
        '  <p>Curated telemetry on distributed systems, high-concurrency tooling, and top engineering news.</p>',
        '</div>',
        '',
        '---',
        '',
        '### <code>( 01 ) // TRENDING REPOSITORIES</code>',
        ''
    ]
    
    for lang, repos in repos_by_lang.items():
        content.append(f"#### **{lang.upper()}**")
        if not repos:
            content.append("_No new high-growth repos indexed._\n")
            continue
        for r in repos:
            content.append(f"- **[{r['name']}]({r['url']})** (`★ {r['stars']}`)")
            content.append(f"  _{r['description']}_\n")
            
    content.append('---')
    content.append('')
    content.append('### <code>( 02 ) // ENGINEERING NEWS & DISCUSSIONS</code>')
    content.append('')
    if hn_stories:
        for s in hn_stories:
            content.append(f"- [{s['title']}]({s['url']}) &nbsp; `▲ {s['score']} pts` &nbsp; `💬 {s['comments']}`")
    content.append('')
    content.append('---')
    content.append('')
    content.append('### <code>( 03 ) // ARCHIVE ACCESS</code>')
    content.append('')
    content.append(f"All previous daily intelligence digests are saved in the [`archive/`](./archive/) folder.")
    content.append('')
    content.append('<div align="center">')
    content.append('  <sub>Maintained automatically by <a href="https://github.com/devodrag">devodrag</a> via GitHub Actions</sub>')
    content.append('</div>')
    
    return "\n".join(content)

def main():
    today = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    print(f"[*] Running Backend Radar for {today}...")
    
    os.makedirs("archive", exist_ok=True)
    
    repos = get_trending_github_repos()
    stories = get_top_hn_stories()
    
    # 1. Write to archive
    archive_path = os.path.join("archive", f"{today}.md")
    archive_md = generate_markdown(today, repos, stories)
    with open(archive_path, "w", encoding="utf-8") as f:
        f.write(archive_md)
    print(f"[+] Saved archive: {archive_path}")
    
    # 2. Update root README.md
    readme_md = update_root_readme(today, repos, stories)
    with open("README.md", "w", encoding="utf-8") as f:
        f.write(readme_md)
    print(f"[+] Updated root README.md")

if __name__ == "__main__":
    main()
